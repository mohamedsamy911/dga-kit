#!/usr/bin/env python3
"""Generates each suite's evals/evals.json from its markdown cases.

`claude plugin eval` looks for `evals/evals.json` INSIDE the skill directory. The cases
themselves stay in markdown under evals/<suite>/cases/ because that is what a human reviews and
argues with - the JSON is a build artefact, never edited by hand. Same contract as tokens.css:
regenerate and let CI diff it.

Usage:  python3 evals/build-evals-json.py [--check]
        --check  regenerate in memory and exit 1 if anything on disk differs
"""
import io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# suite directory name == skill directory name; assert rather than assume, because a rename on
# one side and not the other would silently write evals.json into a skill that does not exist.
SUITES = ('dga-design-review', 'dga-ui-adapter')

# The kit's own bar, restated for the grader on every case: a fabricated DGA rule fails the case
# outright, however good the rest of the answer is. This is the one line that must reach the
# runner - detection score never buys back a fabrication.
BAR = ('Cites DGA for every rule it asserts, and does not invent one: a rule attributed to DGA '
       'that DGA does not publish fails this case regardless of what else the answer gets right.')


def _sections(text):
    """Split a case file into {heading: body} on its `## ` headings."""
    parts = re.split(r'^## +(\w+)\s*$', text, flags=re.M)[1:]
    return {parts[i].lower(): parts[i + 1].strip() for i in range(0, len(parts), 2)}


def _bullets(body):
    """One expectation per top-level `- ` bullet, continuation lines folded in."""
    out = []
    for line in body.split('\n'):
        if re.match(r'^[-*] ', line):
            out.append(line[2:].strip())
        elif out and line.strip():
            out[-1] += ' ' + line.strip()
    return [re.sub(r'\s+', ' ', b) for b in out]


def build(suite):
    cases_dir = os.path.join(ROOT, 'evals', suite, 'cases')
    skill_dir = os.path.join(ROOT, 'skills', suite)
    if not os.path.isdir(skill_dir):
        sys.exit(f'{suite}: no skills/{suite}/ - suite and skill names must match')

    evals = []
    for fn in sorted(os.listdir(cases_dir)):
        if not fn.endswith('.md'):
            continue
        s = _sections(io.open(os.path.join(cases_dir, fn), encoding='utf-8').read())
        missing = [h for h in ('input', 'expect', 'traps') if h not in s]
        if missing:
            sys.exit(f'{suite}/{fn}: missing section(s) {missing}')

        expectations = _bullets(s['expect'])
        if not expectations:
            sys.exit(f'{suite}/{fn}: `## expect` has no `- ` bullets to turn into expectations')

        evals.append({
            'id': int(re.match(r'(\d+)', fn).group(1)),
            'name': re.sub(r'^\d+-', '', fn[:-3]),
            'prompt': f"Use the {suite} skill.\n\n{s['input']}",
            # The trap IS the expected behaviour on these cases - most are written so that the
            # plausible answer is the wrong one, and a grader that never sees the trap marks a
            # confident fabrication as a pass. `## grader` overrides `## traps` where the traps
            # section also carries maintainer history the grader should not read.
            'expected_output': s.get('grader') or s['traps'],
            'expectations': expectations + [BAR],
        })

    return {
        'skill_name': suite,
        '$generated': ('DO NOT EDIT - generated by '
                       'https://github.com/mohamedsamy911/dga-kit/blob/master/evals/build-evals-json.py '
                       'from https://github.com/mohamedsamy911/dga-kit/blob/master/evals/%s/cases/' % suite),
        'evals': evals,
    }


def main():
    check = '--check' in sys.argv
    stale = []
    for suite in SUITES:
        doc = build(suite)
        out = os.path.join(ROOT, 'skills', suite, 'evals', 'evals.json')
        text = json.dumps(doc, indent=2, ensure_ascii=False) + '\n'
        current = io.open(out, encoding='utf-8').read() if os.path.exists(out) else None
        if check:
            if current != text:
                stale.append(os.path.relpath(out, ROOT))
            continue
        os.makedirs(os.path.dirname(out), exist_ok=True)
        io.open(out, 'w', encoding='utf-8', newline='\n').write(text)
        print(f"{os.path.relpath(out, ROOT)}  {len(doc['evals'])} cases")

    if stale:
        print('STALE: ' + ', '.join(stale))
        print('run: python3 evals/build-evals-json.py')
        return 1
    if check:
        print('evals.json is current for both suites')
    return 0


if __name__ == '__main__':
    sys.exit(main())
